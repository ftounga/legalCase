package fr.ailegalcase.casefile;

/**
 * SF-222-03 : modalité de l'habilitation familiale (art. 494-1 Cciv).
 *
 * <ul>
 *   <li>{@code ASSISTANCE} — la personne habilitée assiste le majeur protégé
 *       (besoin léger, le majeur conserve l'exercice de ses droits) ;</li>
 *   <li>{@code REPRESENTATION} — la personne habilitée représente le majeur
 *       protégé (besoin lourd, le majeur ne peut accomplir seul les actes).</li>
 * </ul>
 */
public enum ModaliteHabilitationEnum {
    ASSISTANCE,
    REPRESENTATION
}
